# Strings
a = "Hest"
b = "Ulv"
print(a + b)

# Arrays
c = [1, 2, 3]
d = ["a", "b", "c", "d", "e", "f", "g"]
print(c + d)

# Tupler
e = (4, 5, 6)
f = ("h", "i", "j")
print(e + f)

print(a * 4)
print(c * 3)

print(d[1])
print(d[1:3])
print(d[1:len(d)])
print(d[:3])
print(d[3:])
print(d[1:5:2])
d[4] = "z"
print(d)
